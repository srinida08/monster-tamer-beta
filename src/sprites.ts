// Cache for rendered sprites
const spriteCache = new Map<string, HTMLCanvasElement>()

export function renderMonsterSprite(element: Element, spriteIndex: number, size: number, flipped = false): HTMLCanvasElement {
  const key = `${element}_${spriteIndex}_${size}_${flipped}`
  const cached = spriteCache.get(key)
  if (cached) return cached

  const canvas = document.createElement('canvas')
  canvas.width = size
  canvas.height = size
  const ctx = canvas.getContext('2d')!
  const pal = PALETTES[element]
  const sprites = MONSTER_SPRITES[element]
  const sprite = sprites[spriteIndex % sprites.length]
  const pixelSize = size / 16

  const colorMap: Record<string, string> = {
    '0': '',
    '1': pal.dark,
    '2': pal.primary,
    '3': pal.secondary,
    '4': pal.accent,
    '5': pal.light,
    '6': pal.eye,
  }

  for (let y = 0; y < 16; y++) {
    const row = sprite[y]
    for (let x = 0; x < 16; x++) {
      const c = row[x]
      if (c === '0') continue
      const color = colorMap[c]
      if (!color) continue
      ctx.fillStyle = color
      const drawX = flipped ? (15 - x) * pixelSize : x * pixelSize
      ctx.fillRect(Math.floor(drawX), Math.floor(y * pixelSize), Math.ceil(pixelSize), Math.ceil(pixelSize))
    }
  }

  spriteCache.set(key, canvas)
  return canvas
}

// Draw battle background based on element
export function drawBattleBackground(ctx: CanvasRenderingContext2D, w: number, h: number, element: Element, time: number) {
  const pal = PALETTES[element]

  // Sky gradient
  const grad = ctx.createLinearGradient(0, 0, 0, h * 0.6)
  switch (element) {
    case 'fire':
      grad.addColorStop(0, '#1a0505')
      grad.addColorStop(1, '#4a1500')
      break
    case 'water':
      grad.addColorStop(0, '#0a1a3a')
      grad.addColorStop(1, '#1a4466')
      break
    case 'earth':
      grad.addColorStop(0, '#1a2a0a')
      grad.addColorStop(1, '#2a4a1a')
      break
    case 'wind':
      grad.addColorStop(0, '#1a3a4a')
      grad.addColorStop(1, '#3a6a7a')
      break
    case 'lightning':
      grad.addColorStop(0, '#1a1a05')
      grad.addColorStop(1, '#3a3a1a')
      break
    case 'shadow':
      grad.addColorStop(0, '#0a0515')
      grad.addColorStop(1, '#1a0a2a')
      break
    case 'light':
      grad.addColorStop(0, '#2a2a1a')
      grad.addColorStop(1, '#5a5a2a')
      break
  }
  ctx.fillStyle = grad
  ctx.fillRect(0, 0, w, h * 0.6)

  // Ground
  const groundGrad = ctx.createLinearGradient(0, h * 0.55, 0, h)
  groundGrad.addColorStop(0, pal.dark)
  groundGrad.addColorStop(1, '#0a0a0a')
  ctx.fillStyle = groundGrad
  ctx.fillRect(0, h * 0.55, w, h * 0.45)

  // Ground line
  ctx.fillStyle = pal.primary
  ctx.fillRect(0, Math.floor(h * 0.55), w, 3)

  // Decorative particles based on element
  ctx.globalAlpha = 0.3
  for (let i = 0; i < 12; i++) {
    const px = ((i * 97 + time * 0.02) % (w + 40)) - 20
    const py = h * 0.1 + Math.sin(time * 0.001 + i * 1.5) * h * 0.15
    const s = 2 + (i % 3) * 2
    ctx.fillStyle = pal.accent
    ctx.fillRect(Math.floor(px), Math.floor(py), s, s)
  }
  ctx.globalAlpha = 1
}

// Draw attack effect particles
export interface Particle {
  x: number
  y: number
  vx: number
  vy: number
  life: number
  maxLife: number
  color: string
  size: number
}

export function createAttackParticles(x: number, y: number, element: Element, count: number): Particle[] {
  const pal = PALETTES[element]
  const particles: Particle[] = []
  for (let i = 0; i < count; i++) {
    const angle = (Math.PI * 2 * i) / count + (Math.random() - 0.5) * 0.5
    const speed = 2 + Math.random() * 4
    particles.push({
      x,
      y,
      vx: Math.cos(angle) * speed,
      vy: Math.sin(angle) * speed - 1,
      life: 30 + Math.random() * 20,
      maxLife: 50,
      color: [pal.primary, pal.secondary, pal.accent, pal.light][Math.floor(Math.random() * 4)],
      size: 3 + Math.random() * 5,
    })
  }
  return particles
}

export function updateAndDrawParticles(ctx: CanvasRenderingContext2D, particles: Particle[]): Particle[] {
  const alive: Particle[] = []
  for (const p of particles) {
    p.x += p.vx
    p.y += p.vy
    p.vy += 0.1
    p.life--
    if (p.life <= 0) continue
    ctx.globalAlpha = p.life / p.maxLife
    ctx.fillStyle = p.color
    ctx.fillRect(Math.floor(p.x), Math.floor(p.y), Math.ceil(p.size), Math.ceil(p.size))
    alive.push(p)
  }
  ctx.globalAlpha = 1
  return alive
}

// Draw a slash/hit effect
export function drawSlashEffect(ctx: CanvasRenderingContext2D, x: number, y: number, size: number, progress: number, element: Element) {
  const pal = PALETTES[element]
  ctx.save()
  ctx.translate(x, y)
  ctx.globalAlpha = 1 - progress

  const n = 3
  for (let i = 0; i < n; i++) {
    const angle = (Math.PI * 2 * i) / n + progress * 2
    const len = size * progress
    ctx.strokeStyle = i === 0 ? pal.light : pal.accent
    ctx.lineWidth = 3 - progress * 2
    ctx.beginPath()
    ctx.moveTo(Math.cos(angle) * len * 0.3, Math.sin(angle) * len * 0.3)
    ctx.lineTo(Math.cos(angle) * len, Math.sin(angle) * len)
    ctx.stroke()
  }

  ctx.restore()
}

// Draw floating damage number
